#!/usr/bin/env python3
"""Compile the C programs in rv/ for the DF RISC-V runner and pack them
into src/rvbin.tc.

    python3 tools/rv2tc.py

Each rv/<name>.c (with crt0.S and rv.c) is built for RV32IM with clang and
lld (rv/link.ld: one flat image from address 0) and turned into a flat
binary. The image goes into src/rvbin.tc as text: each 32-bit word is
three characters of a 4,096-character alphabet (12 + 12 + 8 bits), in
chunks of RV_CHUNK words, one function per chunk, so no code template gets
near DF's size limit.

Programs that only use the console calls are also run on tools/rvemu.py
(the reference emulator), and their output is stored as the expected
output for the join tests (rvExpect).
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rvemu  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "rv"
OUT = ROOT / "build" / "rv"
TC = ROOT / "src" / "rvbin.tc"
RUNTIME = ["crt0.S", "rv.c"]
ALPHA_FIRST = 0x4E00
RV_CHUNK = 1000
# Programs that make Wayland calls can't run on the reference emulator.
NO_REFERENCE = {"window"}
CFLAGS = ["--target=riscv32", "-march=rv32im", "-mabi=ilp32", "-mno-relax", "-Os",
          "-ffreestanding", "-fno-builtin", "-nostdlib", "-fno-pic", "-Wall", "-Werror"]


def find_tool(names: list[str]) -> str:
    extra = [Path.home() / ".local/share/swiftly/bin", Path("/usr/lib/llvm-18/bin")]
    for name in names:
        path = shutil.which(name) or next((str(d / name) for d in extra if (d / name).exists()), None)
        if path:
            return path
    sys.exit(f"none of {names} found: install clang and lld with the RISC-V target")


def clang() -> str:
    for cand in [shutil.which("clang"), str(Path.home() / ".local/share/swiftly/bin/clang"), shutil.which("clang-18")]:
        if cand and Path(cand).exists():
            targets = subprocess.run([cand, "-print-targets"], capture_output=True, text=True).stdout
            if "riscv32" in targets:
                return cand
    sys.exit("no clang with the riscv32 target found")


def build(cc: str, objcopy: str, name: str) -> bytes:
    OUT.mkdir(parents=True, exist_ok=True)
    elf = OUT / f"{name}.elf"
    binf = OUT / f"{name}.bin"
    cmd = [cc, *CFLAGS, "-fuse-ld=lld", "-Wl,--image-base=0", "-T", str(SRC / "link.ld"), "-I", str(SRC),
           *[str(SRC / r) for r in RUNTIME], str(SRC / f"{name}.c"), "-o", str(elf)]
    subprocess.run(cmd, check=True)
    subprocess.run([objcopy, "-O", "binary", str(elf), str(binf)], check=True)
    data = binf.read_bytes()
    return data + b"\0" * (-len(data) % 4)


def encode(data: bytes) -> str:
    out = []
    for i in range(0, len(data), 4):
        w = int.from_bytes(data[i : i + 4], "little")
        out.append(chr(ALPHA_FIRST + (w & 4095)) + chr(ALPHA_FIRST + ((w >> 12) & 4095)) + chr(ALPHA_FIRST + (w >> 24)))
    return "".join(out)


def tc_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main() -> None:
    cc = clang()
    objcopy = find_tool(["llvm-objcopy", "llvm-objcopy-18"])
    names = sorted(p.stem for p in SRC.glob("*.c") if p.name not in RUNTIME)
    lines = [
        "// Generated by tools/rv2tc.py from rv/*.c. Do not edit.",
        "",
        f"/** The image alphabet: character k (1-based) is value k - 1, U+{ALPHA_FIRST:04X} on. A word is 3 characters: bits 0-11, 12-23, 24-31. */",
        "function rvAlpha(): str {",
        f"    return {tc_str(''.join(chr(ALPHA_FIRST + k) for k in range(4096)))};",
        "}",
        "",
        "/** The programs, by name. */",
        "function rvPrograms(): list[str] {",
        f"    return [{', '.join(tc_str(n) for n in names)}];",
        "}",
        "",
    ]
    images, expects = {}, {}
    for name in names:
        data = build(cc, objcopy, name)
        if len(data) > rvemu.RAM_BYTES // 2:
            sys.exit(f"{name}: image is {len(data)} bytes; keep it under half the RAM")
        images[name] = encode(data)
        if name not in NO_REFERENCE:
            m = rvemu.run(data)
            expects[name] = m.out.decode("latin-1")
            print(f"{name}: {len(data)} bytes, reference run {m.instret} instructions, exit {m.exit_code}")
        else:
            print(f"{name}: {len(data)} bytes")
    for name, text in images.items():
        chunks = [text[i : i + 3 * RV_CHUNK] for i in range(0, len(text), 3 * RV_CHUNK)]
        for k, chunk in enumerate(chunks):
            lines += [f"function rvImg_{name}_{k}(): str {{", f"    return {tc_str(chunk)};", "}", ""]
        lines += [f"/** {name}'s image: {len(text) // 3} words in {len(chunks)} chunks. */",
                  f"function rvImg_{name}(): list[str] {{",
                  f"    return [{', '.join(f'rvImg_{name}_{k}()' for k in range(len(chunks)))}];", "}", ""]
    lines += ["/** Program `name`'s image as chunks of encoded words, or [] if there is no such program. */",
              "function rvImage(name: str): list[str] {"]
    for i, name in enumerate(images):
        lines += [f"    {'if' if i == 0 else '} else if'} (name == {tc_str(name)}) {{", f"        return rvImg_{name}();"]
    lines += ["    }", "    return list.create() as list[str];", "}", "",
              "/** What program `name` prints, from the reference emulator (tools/rvemu.py); \"\" if it has none. */",
              "function rvExpect(name: str): str {"]
    for i, (name, text) in enumerate(expects.items()):
        lines += [f"    {'if' if i == 0 else '} else if'} (name == {tc_str(name)}) {{", f"        return {tc_str(text)};"]
    lines += ["    }", '    return "";', "}", ""]
    TC.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {TC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
