#!/usr/bin/env python3
"""Generate src/font8.tc, an 8x8 bitmap font for printable ASCII.

    python3 tools/font2tc.py [font.psf.gz]

The default is the console font Lat15-VGA8. Each character (32 to 126) is 8
row bytes, the leftmost pixel in bit 7.
"""

from __future__ import annotations

import gzip
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = "/usr/share/consolefonts/Lat15-VGA8.psf.gz"


def load_psf1(path: str) -> dict[int, bytes]:
    data = gzip.open(path).read()
    if data[:2] != b"\x36\x04":
        sys.exit("not a PSF1 font")
    mode, size = data[2], data[3]
    count = 512 if mode & 1 else 256
    glyphs = [data[4 + i * size: 4 + (i + 1) * size] for i in range(count)]
    table = {}
    if mode & 2:
        pos = 4 + count * size
        for i in range(count):
            while True:
                cp = int.from_bytes(data[pos:pos + 2], "little")
                pos += 2
                if cp == 0xFFFF:
                    break
                if cp != 0xFFFE:
                    table.setdefault(cp, glyphs[i])
    else:
        table = {i: g for i, g in enumerate(glyphs)}
    return table


def main() -> None:
    table = load_psf1(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
    rows = []
    for cp in range(32, 127):
        glyph = table.get(cp) or table[ord("?")]
        if len(glyph) != 8:
            sys.exit(f"glyph {cp} is {len(glyph)} rows, expected 8")
        rows.extend(glyph)
    body = []
    for i in range(0, len(rows), 16):
        body.append("        " + ", ".join(str(r) for r in rows[i:i + 16]) + ",")
    body[-1] = body[-1].rstrip(",")
    text = f"""// Generated by tools/font2tc.py from Lat15-VGA8. Do not edit.

/** 8x8 font rows for characters 32 to 126: row r (0-7) of character n is at index (n - 32) * 8 + r + 1, leftmost pixel in bit 7. */
function fontRows(): list[num] {{
    return [
{chr(10).join(body)}
    ];
}}
"""
    (ROOT / "src" / "font8.tc").write_text(text, encoding="utf-8")
    print("wrote src/font8.tc")


if __name__ == "__main__":
    main()
