#!/usr/bin/env python3
"""Generate src/protocol.tc from the Wayland protocol XML.

    python3 tools/protocol2tc.py [wayland.xml] [xdg-shell.xml] [df-shell.xml]

Defaults are the system copies in /usr/share and this repo's
protocol/df-shell.xml (the desktop shell's own protocol). Only the interfaces in IFACES
are kept, so the tables stay small.

Each message becomes one string: its name, then one token per argument:

    i int   u uint   f fixed   s string   a array   h fd
    o:<iface> object   n:<iface> new_id   N untyped new_id (string, uint, new_id on the wire)

The tables are dicts (wlProtoInit fills them):

    wl.req["<iface>"], wl.ev["<iface>"]   list of message strings, opcode + 1
    wl.reqop["<iface>.<name>"]            request opcode
    wl.evop["<iface>.<name>"]             event opcode
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULTS = [
    "/usr/share/wayland/wayland.xml",
    "/usr/share/wayland-protocols/stable/xdg-shell/xdg-shell.xml",
    str(ROOT / "protocol" / "df-shell.xml"),
]
IFACES = [
    "wl_display", "wl_registry", "wl_callback", "wl_compositor", "wl_shm_pool",
    "wl_shm", "wl_buffer", "wl_surface", "wl_region", "wl_seat", "wl_pointer",
    "wl_keyboard", "wl_output", "xdg_wm_base", "xdg_surface", "xdg_toplevel",
    "df_shell", "df_panel",
]
CODES = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "array": "a", "fd": "h"}


def message(elem: ET.Element) -> str:
    tokens = [elem.get("name")]
    for arg in elem.findall("arg"):
        kind = arg.get("type")
        if kind == "object":
            tokens.append(f"o:{arg.get('interface', '')}")
        elif kind == "new_id":
            tokens.append(f"n:{arg.get('interface')}" if arg.get("interface") else "N")
        else:
            tokens.append(CODES[kind])
    return " ".join(tokens)


def tc_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    paths = sys.argv[1:] or DEFAULTS
    ifaces = {}
    for path in paths:
        for iface in ET.parse(path).getroot().findall("interface"):
            if iface.get("name") in IFACES:
                ifaces[iface.get("name")] = iface
    missing = [n for n in IFACES if n not in ifaces]
    if missing:
        sys.exit(f"missing interfaces: {missing}")

    lines = [
        "// Generated by tools/protocol2tc.py from wayland.xml, xdg-shell.xml and df-shell.xml. Do not edit.",
        "",
        "/** Request and event signatures by interface (opcode + 1), and opcodes by \"<iface>.<name>\". */",
        'declare global "wl.req": dict[list[str]];',
        'declare global "wl.ev": dict[list[str]];',
        'declare global "wl.reqop": dict[num];',
        'declare global "wl.evop": dict[num];',
        "",
        "/** Fills the protocol tables. */",
        "function wlProtoInit {",
        "    line req: dict[list[str]] = {};",
        "    line ev: dict[list[str]] = {};",
        "    line reqop: dict[num] = {};",
        "    line evop: dict[num] = {};",
    ]
    for name in IFACES:
        iface = ifaces[name]
        for kind, table, ops in (("request", "req", "reqop"), ("event", "ev", "evop")):
            msgs = [message(m) for m in iface.findall(kind)]
            lines.append(f"    {table}[{tc_str(name)}] = [{', '.join(tc_str(m) for m in msgs)}];")
            for op, m in enumerate(iface.findall(kind)):
                lines.append(f"    {ops}[{tc_str(name + '.' + m.get('name'))}] = {op};")
    lines += [
        '    global "wl.req" = req;',
        '    global "wl.ev" = ev;',
        '    global "wl.reqop" = reqop;',
        '    global "wl.evop" = evop;',
        "}",
        "",
    ]
    out = ROOT / "src" / "protocol.tc"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {len(IFACES)} interfaces")


if __name__ == "__main__":
    main()
