#!/usr/bin/env python3
"""Generate the pixel-glyph font wl:px and its Terracotta tables.

    python3 pack/src/px_assets.py

Writes:
  pack/assets/wl/textures/font/px_argb8888.png  256 glyphs, 10x10 texels
  pack/assets/wl/textures/font/px_rgb332.png    256 glyphs, 40x10 texels
  pack/assets/wl/font/px.json                   the font (two bitmap providers)
  src/glyphs.tc                                 glyph and hex tables for DF

A pixel glyph carries one 32-bit buffer word (wl:px.glsl decodes it): the text
color holds the low 24 bits and the glyph's texels hold the top byte, a marker
and the glyph's format and sub-pixel:

    red = word >> 24, green = MARK, blue = 0xA0 | format << 2 | sub-pixel

Each cell's last texel column has alpha 0. The bitmap provider then measures
the glyph one column narrower, so its advance (width + 1) equals the quad
width and glyphs tile with no gap. Its RGB still carries the data, so the
shader paints it too. Cells are 10 texels tall at height 10, the same as a
text display's line height, so rows tile too.
"""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "pack" / "assets" / "wl"

MARK = 0xC3
# (name, format id, first codepoint, texels per sub-pixel, sub-pixels per glyph)
FORMATS = [
    ("argb8888", 0, 0xE000, 10, 1),
    ("rgb332", 1, 0xE100, 10, 4),
]
CELL_H = 10


def glyph_sheet(fmt: int, sub_w: int, subs: int) -> Image.Image:
    cell_w = sub_w * subs
    img = Image.new("RGBA", (16 * cell_w, 16 * CELL_H))
    px = img.load()
    for i in range(256):
        x0, y0 = (i % 16) * cell_w, (i // 16) * CELL_H
        for x in range(cell_w):
            alpha = 0 if x == cell_w - 1 else 255
            blue = 0xA0 | fmt << 2 | x // sub_w
            for y in range(CELL_H):
                px[x0 + x, y0 + y] = (i, MARK, blue, alpha)
    return img


def font_json() -> dict:
    providers = []
    for name, _, first, _, _ in FORMATS:
        rows = ["".join(chr(first + r * 16 + c) for c in range(16)) for r in range(16)]
        providers.append({
            "type": "bitmap",
            "file": f"wl:font/px_{name}.png",
            "height": CELL_H,
            "ascent": 8,
            "chars": rows,
        })
    return {"providers": providers}


def glyphs_tc() -> str:
    def tc_list(items: list[str]) -> str:
        lines = []
        for r in range(0, len(items), 16):
            lines.append("        " + ", ".join(f'"{s}"' for s in items[r:r + 16]) + ",")
        lines[-1] = lines[-1].rstrip(",")
        return "\n".join(lines)

    glyphs = [chr(first + i) for _, _, first, _, _ in FORMATS for i in range(256)]
    hexes = [f"{i:02x}" for i in range(256)]
    return f"""// Generated by pack/src/px_assets.py. Do not edit.

/**
 * Pixel glyphs of font wl:px, 256 per format: index format * 256 + top byte + 1
 * (argb8888 is format 0, rgb332 format 1).
 */
function pxGlyphTable(): list[str] {{
    return [
{tc_list(glyphs)}
    ];
}}

/** Two-digit lowercase hex for 0-255, at index value + 1. */
function pxHexTable(): list[str] {{
    return [
{tc_list(hexes)}
    ];
}}
"""


def main() -> None:
    tex = ASSETS / "textures" / "font"
    tex.mkdir(parents=True, exist_ok=True)
    for name, fmt, _, sub_w, subs in FORMATS:
        glyph_sheet(fmt, sub_w, subs).save(tex / f"px_{name}.png", optimize=True)
    (ASSETS / "font").mkdir(parents=True, exist_ok=True)
    (ASSETS / "font" / "px.json").write_text(json.dumps(font_json(), indent=2) + "\n", encoding="utf-8")
    (ROOT / "src").mkdir(exist_ok=True)
    (ROOT / "src" / "glyphs.tc").write_text(glyphs_tc(), encoding="utf-8")
    print("wrote wl:px font, textures and src/glyphs.tc")


if __name__ == "__main__":
    main()
